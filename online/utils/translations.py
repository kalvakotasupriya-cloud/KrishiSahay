def get_ui_string(lang_code: str, key: str) -> str:
    """Get a UI string for the given language, falling back to English."""
    lang_strings = UI_STRINGS.get(lang_code, UI_STRINGS["en"])
    return lang_strings.get(key, UI_STRINGS["en"].get(key, key))

